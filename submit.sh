#!/usr/bin/env bash
# Submitter for the 10703_pj baseline-acquisition + gap-analysis pipeline.
# It ONLY calls sbatch. It does no work of its own.
#
# Config travels as ONE timestamped env file passed as a POSITIONAL ARGUMENT.
# We never use `sbatch --export`: any explicit export list makes sbatch set
# SLURM_GET_USER_ENV=1, slurmd fails to rebuild the login env on the compute
# node, and the job is requeued+held, stranding every dependent on Dependency.
#
# Usage:
#   ./submit.sh                      # full DAG
#   ./submit.sh fetch                # downloads + env build only
#   ./submit.sh analyze              # profile + figures only (data already there)
#   ./submit.sh figures              # redraw figures from existing artifacts
#   ./submit.sh gen                  # generalization headroom (unseen gene/combo/context) + figures
#   ./submit.sh rl                   # is the unseen-gene gap RL-shaped? objective + acquisition headroom
#   ./submit.sh genfigs              # redraw only the generalization figures
#   ./submit.sh rlacq                # RL on the acquisition gap: cache, baselines, training array, report
#   ./submit.sh rlacq_train          # same, reusing the cache; rlacq_report redraws the report only
#   ./submit.sh rlacq_runs           # training array + report only (baselines already there)
#   PJ_RLA_SMOKE=1 ./submit.sh rlacq_smoke   # training array only, 3 iterations: code-path check
#   ./submit.sh related              # published methods on the RL task: fetch, priors, array, report
#   ./submit.sh related_runs         # same, reusing the fetched code/kernels and aligned priors
#   ./submit.sh related_fetch        # fetch + prior alignment only
#   PJ_REL_SMOKE=1 ./submit.sh related_smoke  # array only, 300 reward evaluations, separate output dir
#   ./submit.sh story                # gap/improvement case studies: data (CPU) -> fig18-fig21
#   ./submit.sh storyfigs            # redraw fig18-fig21 from artifacts/story/ only (cheap)
#   ./submit.sh paperfigs            # re-render fig13/15/16/17 in the fig18-21 journal style (cheap)
#   ./submit.sh reprprobe            # why the unseen-gene predictor fails: class ceiling / GO ordering / geometry
#   ./submit.sh reprpred             # swap the predictor's gene representation: priors vs GO vs learned
#   ./submit.sh reprsel              # ranking neighbours vs combining them: knn average vs ridge vs MMR
#   FETCH_PDG_CHEMICAL=1 ./submit.sh # also pull the 37 GB chemical tarball
set -euo pipefail

PJ_HOME="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PJ_SCRATCH="${PJ_SCRATCH:-/zfsauton/scratch/yixiz/10703_pj}"
STAGE="${1:-all}"

mkdir -p "$PJ_SCRATCH/envfiles" "$PJ_SCRATCH/logs"

# Scrub SLURM_* from our own environment: if submit.sh is run from inside an
# allocation, inherited SLURM_* vars confuse the child job's accounting.
for v in $(env | sed -n 's/^\(SLURM_[A-Z_]*\)=.*/\1/p'); do unset "$v" || true; done

STAMP="$(date +%Y%m%d_%H%M%S)"
ENVFILE="$PJ_SCRATCH/envfiles/env_${STAMP}.sh"

cat > "$ENVFILE" <<EOF
# generated by submit.sh at $(date -Is) on $(hostname) -- do not edit
export PJ_HOME='$PJ_HOME'
export PJ_SCRATCH='$PJ_SCRATCH'
export PJ_RUN_STAMP='$STAMP'
export FETCH_PDG_CHEMICAL='${FETCH_PDG_CHEMICAL:-0}'
export PJ_PY_TORCH='${PJ_PY_TORCH:-/zfsauton/scratch/yixiz/envs/pertrl/bin/python}'
export PJ_RL_PARTS='${PJ_RL_PARTS:-}'
export PJ_RL_RANDOM_ONLY='${PJ_RL_RANDOM_ONLY:-}'
EOF
# RL-acquisition knobs: write ONLY the ones set here, so env/common.sh stays the
# single source of their defaults (an empty export would override a default).
for v in PJ_REPR_KNN PJ_RLA_DATASETS PJ_RLA_SPLITS PJ_RLA_METHODS PJ_RLA_SEEDS PJ_RLA_PER_TASK PJ_RLA_MAXPAR \
         PJ_RLA_SMOKE PJ_RLA_FORCE PJ_RLA_PPO_ITERS PJ_RLA_PPO_UNIV PJ_RLA_PPO_GROUP \
         PJ_RLA_PPO_EPOCHS PJ_RLA_PPO_LR PJ_RLA_PPO_ENT PJ_RLA_NVAL PJ_RLA_VAL_EVERY \
         PJ_RLA_PG_ITERS PJ_RLA_CRITIC_UNIV PJ_RLA_CRITIC_EPOCHS \
         PJ_REL_METHODS PJ_REL_SEEDS PJ_REL_PER_TASK PJ_REL_MAXPAR PJ_REL_NEVAL PJ_REL_SMOKE PJ_REL_FORCE \
         PJ_STORY_FORCE; do
  if [ -n "${!v:-}" ]; then printf "export %s='%s'\n" "$v" "${!v}" >> "$ENVFILE"; fi
done

echo "env file : $ENVFILE"
cat "$ENVFILE" | sed 's/^/           /'
echo ""

J="$PJ_HOME/jobs"
sub() { # sub <script> [dep-spec]
  local script="$1"; shift
  local dep=("$@")
  local cmd=(sbatch --parsable)
  [ ${#dep[@]} -gt 0 ] && cmd+=("${dep[@]}")
  cmd+=("$script" "$ENVFILE")
  echo "+ ${cmd[*]}" >&2
  "${cmd[@]}"
}

declare -A ID

if [ "$STAGE" = "all" ] || [ "$STAGE" = "fetch" ]; then
  # Independent siblings -> queue concurrently.
  ID[code]=$(sub "$J/10_fetch_code.sbatch")
  ID[gears]=$(sub "$J/11_fetch_gears_data.sbatch")
  ID[pdg]=$(sub "$J/12_fetch_pdgrapher_data.sbatch")
  ID[env]=$(sub "$J/13_build_torch_env.sbatch")
  echo ""
  printf '  %-10s %s\n' code "${ID[code]}" gears "${ID[gears]}" pdg "${ID[pdg]}" env "${ID[env]}"
fi

if [ "$STAGE" = "all" ]; then
  # Profiling needs the GEARS h5ads (afterok) and benefits from PDGrapher splits
  # (afterany: a PDGrapher failure must not block the perturb-seq profiling).
  ID[profile]=$(sub "$J/20_profile.sbatch" \
      "--dependency=afterok:${ID[gears]},afterany:${ID[pdg]}:${ID[code]}")
  # Oracle probe needs data + env; both afterany, the job gates internally.
  ID[oracle]=$(sub "$J/21_oracle_probe.sbatch" \
      "--dependency=afterany:${ID[gears]}:${ID[env]}")
  # Figures read artifacts only; afterany so partial results still get drawn.
  ID[figs]=$(sub "$J/30_figures.sbatch" \
      "--dependency=afterany:${ID[profile]}:${ID[oracle]}")
  echo ""
  printf '  %-10s %s\n' profile "${ID[profile]}" oracle "${ID[oracle]}" figures "${ID[figs]}"
fi

if [ "$STAGE" = "analyze" ]; then
  ID[profile]=$(sub "$J/20_profile.sbatch")
  ID[oracle]=$(sub "$J/21_oracle_probe.sbatch")
  ID[figs]=$(sub "$J/30_figures.sbatch" \
      "--dependency=afterany:${ID[profile]}:${ID[oracle]}")
  printf '  %-10s %s\n' profile "${ID[profile]}" oracle "${ID[oracle]}" figures "${ID[figs]}"
fi

if [ "$STAGE" = "gen" ]; then
  # Headroom along the unseen-gene / unseen-combo / unseen-context axes, then
  # its figures. afterany: the figure job gates on the artifact itself.
  ID[gen]=$(sub "$J/25_generalization.sbatch")
  ID[genfig]=$(sub "$J/33_generalization_figures.sbatch" "--dependency=afterany:${ID[gen]}")
  printf '  %-10s %s\n' gen "${ID[gen]}" genfig "${ID[genfig]}"
fi

if [ "$STAGE" = "rl" ]; then
  # Is the unseen-gene gap RL-shaped? objective headroom + acquisition headroom.
  ID[rl]=$(sub "$J/26_rl_headroom.sbatch")
  printf '  %-10s %s\n' rl "${ID[rl]}"
fi

# Grid sizes for the RL-acquisition arrays, read from the SAME defaults and
# overrides the jobs will see (env/common.sh, then this submission's env file).
rla_grid() {  # rla_grid train|base -> "<n_tasks> <maxpar>"
  ( set +u
    # shellcheck disable=SC1091
    . "$PJ_HOME/env/common.sh"
    # shellcheck disable=SC1090
    . "$ENVFILE"
    nd=$(wc -w <<<"$PJ_RLA_DATASETS"); ns=$(wc -w <<<"$PJ_RLA_SPLITS")
    nm=$(wc -w <<<"$PJ_RLA_METHODS"); nz=$(wc -w <<<"$PJ_RLA_SEEDS")
    # one array task runs PJ_RLA_PER_TASK grid entries (array tasks count against the QOS submit limit)
    n=$((nd * ns * nm * nz)); per=$PJ_RLA_PER_TASK
    if [ "$1" = train ]; then echo "$(((n + per - 1) / per)) $PJ_RLA_MAXPAR"; else echo "$((nd * ns)) 0"; fi )
}

if [ "$STAGE" = "rlcache" ]; then
  # cache + reproduction check only
  ID[rlcache]=$(sub "$J/40_rl_cache.sbatch")
  printf '  %-10s %s\n' rlcache "${ID[rlcache]}"
fi

if [ "$STAGE" = "rlacq" ] || [ "$STAGE" = "rlacq_train" ] || [ "$STAGE" = "rlacq_runs" ]; then
  # RL on the acquisition gap. rlacq builds the cache first; rlacq_train reuses it;
  # rlacq_runs submits only training + report (baselines already done or running).
  # Baselines and training are siblings (both only need the cache); the report
  # reads whatever finished (afterany) and says what is missing.
  read -r NT MAXPAR < <(rla_grid train)
  read -r NB _ < <(rla_grid base)
  DEP=()
  if [ "$STAGE" = "rlacq" ]; then
    ID[rlcache]=$(sub "$J/40_rl_cache.sbatch")
    DEP=("--dependency=afterok:${ID[rlcache]}")
  fi
  AFTER=""
  if [ "$STAGE" != "rlacq_runs" ]; then
    ID[rlbase]=$(sub "$J/41_rl_baselines.sbatch" ${DEP[@]+"${DEP[@]}"} "--array=0-$((NB - 1))")
    AFTER=":${ID[rlbase]}"
  fi
  ID[rltrain]=$(sub "$J/42_rl_train.sbatch" ${DEP[@]+"${DEP[@]}"} "--array=0-$((NT - 1))%${MAXPAR}")
  ID[rlreport]=$(sub "$J/43_rl_report.sbatch" "--dependency=afterany${AFTER}:${ID[rltrain]}")
  printf '  %-10s %s\n' rlcache "${ID[rlcache]:-<reused>}" rlbase "${ID[rlbase]:-<not submitted>}" \
    rltrain "${ID[rltrain]} (${NT} tasks, ${MAXPAR} at a time)" rlreport "${ID[rlreport]}"
fi

if [ "$STAGE" = "rlacq_base" ]; then
  # Baselines array only. Needed on its own because PJ_RLA_FORCE is read by BOTH the
  # baselines and the training job, so re-running the baselines to add a strategy
  # must not also redo every finished RL run. The baselines are deterministic (fixed
  # seeds), so a forced re-run reproduces the existing rows and adds the new ones.
  read -r NB _ < <(rla_grid base)
  ID[rlbase]=$(sub "$J/41_rl_baselines.sbatch" "--array=0-$((NB - 1))")
  printf '  %-10s %s\n' rlbase "${ID[rlbase]} (${NB} tasks)"
fi

if [ "$STAGE" = "rlacq_smoke" ]; then
  # Training array only, no report: a cheap end-to-end check of the RL code paths
  # (and, since PJ_RLA_SMOKE shrinks only the ITERATION COUNT and not the
  # sub-problems, a measurement of per-iteration cost at real scale, which is how
  # the real run's --time is sized). Results land in artifacts/rl_acquire_smoke/.
  read -r NT MAXPAR < <(rla_grid train)
  ID[rltrain]=$(sub "$J/42_rl_train.sbatch" "--array=0-$((NT - 1))%${MAXPAR}")
  printf '  %-10s %s\n' rltrain "${ID[rltrain]} (${NT} tasks, ${MAXPAR} at a time)"
fi

# Related work on the RL acquisition task (scripts/related_work.py). Array size from the
# same defaults + overrides the job sees, like rla_grid.
rel_grid() {  # -> "<n_tasks> <maxpar>"
  ( set +u
    # shellcheck disable=SC1091
    . "$PJ_HOME/env/common.sh"
    # shellcheck disable=SC1090
    . "$ENVFILE"
    n=$(( $(wc -w <<<"$PJ_RLA_DATASETS") * $(wc -w <<<"$PJ_RLA_SPLITS") \
        * $(wc -w <<<"$PJ_REL_METHODS") * $(wc -w <<<"$PJ_REL_SEEDS") ))
    echo "$(((n + PJ_REL_PER_TASK - 1) / PJ_REL_PER_TASK)) $PJ_REL_MAXPAR" )
}

if [ "$STAGE" = "related" ] || [ "$STAGE" = "related_runs" ] || [ "$STAGE" = "related_smoke" ]; then
  # related:       fetch code + IterPert kernels -> align priors -> run array -> report
  # related_runs:  run array -> report (fetch and priors already there)
  # related_smoke: run array only, PJ_REL_SMOKE=1 recommended (300 reward evaluations,
  #                results to artifacts/rl_acquire/related_smoke/, never read by the report)
  # The report runs afterany so it prints partial results and lists failed runs.
  read -r NT MAXPAR < <(rel_grid)
  DEP=()
  if [ "$STAGE" = "related" ]; then
    ID[relfetch]=$(sub "$J/14_fetch_related.sbatch")
    ID[relprep]=$(sub "$J/44_related_prep.sbatch" "--dependency=afterok:${ID[relfetch]}")
    DEP=("--dependency=afterok:${ID[relprep]}")
  fi
  ID[relrun]=$(sub "$J/45_related_run.sbatch" ${DEP[@]+"${DEP[@]}"} "--array=0-$((NT - 1))%${MAXPAR}")
  if [ "$STAGE" != "related_smoke" ]; then
    ID[rlreport]=$(sub "$J/43_rl_report.sbatch" "--dependency=afterany:${ID[relrun]}")
  fi
  printf '  %-10s %s\n' relfetch "${ID[relfetch]:-<reused>}" relprep "${ID[relprep]:-<reused>}" \
    relrun "${ID[relrun]} (${NT} tasks, ${MAXPAR} at a time)" rlreport "${ID[rlreport]:-<not submitted>}"
fi

if [ "$STAGE" = "related_fetch" ]; then
  # fetch + prior alignment only
  ID[relfetch]=$(sub "$J/14_fetch_related.sbatch")
  ID[relprep]=$(sub "$J/44_related_prep.sbatch" "--dependency=afterok:${ID[relfetch]}")
  printf '  %-10s %s\n' relfetch "${ID[relfetch]}" relprep "${ID[relprep]}"
fi

if [ "$STAGE" = "rlacq_report" ]; then
  ID[rlreport]=$(sub "$J/43_rl_report.sbatch")
  printf '  %-10s %s\n' rlreport "${ID[rlreport]}"
fi

if [ "$STAGE" = "story" ]; then
  # Case-study data (per-gene ranks, neighbourhoods, greedy's per-step gains), then the
  # figures. afterany: the figure job gates on the npz itself and says what is missing.
  ID[storydata]=$(sub "$J/46_story_data.sbatch")
  ID[storyfigs]=$(sub "$J/47_story_figs.sbatch" "--dependency=afterany:${ID[storydata]}")
  printf '  %-10s %s\n' storydata "${ID[storydata]}" storyfigs "${ID[storyfigs]}"
fi

if [ "$STAGE" = "storyfigs" ]; then
  ID[storyfigs]=$(sub "$J/47_story_figs.sbatch")
  printf '  %-10s %s\n' storyfigs "${ID[storyfigs]}"
fi

if [ "$STAGE" = "paperfigs" ]; then
  # Re-render fig13/fig15/fig16/fig17 in the journal style of fig18-fig21, from
  # saved artifacts only (so every figure in a write-up looks the same). Cheap.
  ID[paperfigs]=$(sub "$J/48_paper_figs.sbatch")
  printf '  %-10s %s\n' paperfigs "${ID[paperfigs]}"
fi

if [ "$STAGE" = "reprprobe" ]; then
  # Failure anatomy of the unseen-gene predictor: predictor-class ceiling vs GO's
  # ordering vs scoring geometry. Reads the RL cache + the GEARS h5ad only. CPU.
  ID[reprprobe]=$(sub "$J/50_repr_probe.sbatch")
  printf '  %-10s %s\n' reprprobe "${ID[reprprobe]}"
fi

if [ "$STAGE" = "reprpred" ]; then
  # Swap the unseen-gene predictor's similarity: GO Jaccard vs IterPert's released
  # multimodal priors vs a learned out-of-fold combination, against the ceilings.
  ID[reprpred]=$(sub "$J/51_repr_predict.sbatch")
  printf '  %-10s %s\n' reprpred "${ID[reprpred]}"
fi

if [ "$STAGE" = "reprsel" ]; then
  # Ranking the neighbours vs combining them: {GO, learned priors, oracle} x
  # {knn average, ridge over the atlas Gram, MMR}, hyper-parameters chosen out of fold.
  ID[reprsel]=$(sub "$J/52_repr_select.sbatch")
  printf '  %-10s %s\n' reprsel "${ID[reprsel]}"
fi

if [ "$STAGE" = "genfigs" ]; then
  ID[genfig]=$(sub "$J/33_generalization_figures.sbatch")
  printf '  %-10s %s\n' genfig "${ID[genfig]}"
fi

if [ "$STAGE" = "figures" ]; then
  ID[figs]=$(sub "$J/30_figures.sbatch")
  printf '  %-10s %s\n' figures "${ID[figs]}"
fi

echo ""
echo "logs: $PJ_SCRATCH/logs/"
echo "watch: squeue -u \$USER -o '%.8i %.9P %.16j %.8T %.10M %R'"
